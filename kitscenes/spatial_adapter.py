"""Spatial Conditioning Adapter for Stable Video Diffusion (SVD-XT).

Provides a lightweight, zero-initialized spatial trajectory conditioning adapter
for Stable Video Diffusion (SVD-XT) and multi-scale UNet backbones:
- Takes 5D spatial control mask tensors [B, T, 1, H, W] or 4D static masks [B, 1, H, W].
- Encodes masks through a 4-block downsampling ConvNet with SiLU and zero-conv output
  to match SVD-XT UNet latent resolution [B, T, C_latent, H/8, W/8] or UNet down-blocks.
- Supports conditioning via:
  a) Latent addition (residual addition to noisy video latents before UNet).
  b) Latent concatenation (channel concatenation to input latents).
  c) Feature injection into UNet down-block residuals (ControlNet-style zero-convs).
- Freezes the entire pretrained SVD-XT backbone (UNet, VAE, CLIP image encoder)
  so ONLY the lightweight adapter parameters (< 5-10M parameters) are trained.
- Includes a lightweight mock UNet for fast, self-contained CPU testing.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple, Union

import torch
import torch.nn as nn
import torch.nn.functional as F


# ==============================================================================
# 1. CONFIGURATION & OUTPUT CONTAINERS
# ==============================================================================


@dataclass
class SpatialAdapterConfig:
    """Configuration for the SVD-XT Spatial Conditioning Adapter."""

    in_channels: int = 1
    adapter_channels: Tuple[int, ...] = (32, 64, 128, 256)
    latent_channels: int = 4
    down_block_channels: Tuple[int, ...] = (320, 640, 1280, 1280)
    conditioning_type: str = "latent_addition"  # "latent_addition" | "latent_concat" | "residual_injection"
    use_temporal_conv: bool = True
    zero_conv_init: bool = True
    dropout: float = 0.0


@dataclass
class SpatialAdapterOutput:
    """Container for features generated by SpatialAdapter."""

    latent_conditioning: torch.Tensor
    down_block_residuals: Optional[List[torch.Tensor]] = None
    conditioning_type: str = "latent_addition"
    metadata: Dict[str, Any] = field(default_factory=dict)


# ==============================================================================
# 2. ZERO-CONVOLUTION MODULES
# ==============================================================================


class ZeroConv2d(nn.Module):
    """2D Convolution with weights and biases initialized strictly to zeros.

    Preserves exact pretrained model behavior at step 0 of fine-tuning (ControlNet principle).
    """

    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: int = 3,
        stride: int = 1,
        padding: int = 1,
    ) -> None:
        super().__init__()
        self.conv = nn.Conv2d(
            in_channels,
            out_channels,
            kernel_size=kernel_size,
            stride=stride,
            padding=padding,
        )
        nn.init.zeros_(self.conv.weight)
        if self.conv.bias is not None:
            nn.init.zeros_(self.conv.bias)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.conv(x)


class ZeroConv1d(nn.Module):
    """1D Temporal Convolution with weights and biases initialized strictly to zeros."""

    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: int = 3,
        stride: int = 1,
        padding: int = 1,
    ) -> None:
        super().__init__()
        self.conv = nn.Conv1d(
            in_channels,
            out_channels,
            kernel_size=kernel_size,
            stride=stride,
            padding=padding,
        )
        nn.init.zeros_(self.conv.weight)
        if self.conv.bias is not None:
            nn.init.zeros_(self.conv.bias)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.conv(x)


