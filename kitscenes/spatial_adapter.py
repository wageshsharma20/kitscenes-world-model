# 3. SPATIAL ADAPTER ARCHITECTURE
# ==============================================================================


class SpatialAdapter(nn.Module):
    """Lightweight Spatial Conditioning Adapter for SVD-XT.

    Encodes trajectory conditioning masks [B, T, 1, H, W] into latent-space features
    [B, T, C_latent, H/8, W/8] and multi-scale down-block residuals.
    """

    def __init__(self, config: Optional[SpatialAdapterConfig] = None) -> None:
        super().__init__()
        self.config = config or SpatialAdapterConfig()

        in_ch = self.config.in_channels
        c0, c1, c2, c3 = self.config.adapter_channels

        # 4-block downsampling ConvNet (8x spatial downsampling matching VAE)
        # Block 1: 1 -> c0 (stride 2: H -> H/2, W -> W/2)
        self.block1 = nn.Sequential(
            nn.Conv2d(in_ch, c0, kernel_size=3, stride=2, padding=1),
            nn.GroupNorm(min(8, c0), c0),
            nn.SiLU(),
        )

        # Block 2: c0 -> c1 (stride 2: H/2 -> H/4, W/2 -> W/4)
        self.block2 = nn.Sequential(
            nn.Conv2d(c0, c1, kernel_size=3, stride=2, padding=1),
            nn.GroupNorm(min(8, c1), c1),
            nn.SiLU(),
        )

        # Block 3: c1 -> c2 (stride 2: H/4 -> H/8, W/4 -> W/8)
        self.block3 = nn.Sequential(
            nn.Conv2d(c1, c2, kernel_size=3, stride=2, padding=1),
            nn.GroupNorm(min(8, c2), c2),
            nn.SiLU(),
        )

        # Block 4: c2 -> c3 (stride 1: maintains H/8, W/8)
        self.block4 = nn.Sequential(
            nn.Conv2d(c2, c3, kernel_size=3, stride=1, padding=1),
            nn.GroupNorm(min(8, c3), c3),
            nn.SiLU(),
        )

        # Optional 1D Temporal Convolution (operates across frames T with residual)
        if self.config.use_temporal_conv:
            self.temporal_conv = ZeroConv1d(c3, c3, kernel_size=3, padding=1)
        else:
            self.temporal_conv = None

        # Latent Output Head (zero-conv output to match latent channels, e.g. 4)
        if self.config.zero_conv_init:
            self.latent_head = ZeroConv2d(c3, self.config.latent_channels, kernel_size=3, stride=1, padding=1)
        else:
            self.latent_head = nn.Conv2d(c3, self.config.latent_channels, kernel_size=3, stride=1, padding=1)

        # Multi-scale Residual Injection Heads (matching UNet down-blocks)
        if self.config.conditioning_type == "residual_injection":
            down_ch = self.config.down_block_channels
            self.residual_heads = nn.ModuleList([
                ZeroConv2d(c0, down_ch[0], kernel_size=3, stride=1, padding=1),
                ZeroConv2d(c1, down_ch[1], kernel_size=3, stride=1, padding=1),
                ZeroConv2d(c2, down_ch[2], kernel_size=3, stride=1, padding=1),
                ZeroConv2d(c3, down_ch[3], kernel_size=3, stride=1, padding=1),
            ])
        else:
            self.residual_heads = None

    @property
    def parameter_count(self) -> int:
        """Total trainable parameters in the spatial adapter."""
        return sum(p.numel() for p in self.parameters() if p.requires_grad)

    def forward(
        self,
        masks: torch.Tensor,
        target_latent_shape: Optional[Tuple[int, int]] = None,
        num_frames: Optional[int] = None,
    ) -> SpatialAdapterOutput:
        """Encode control masks into latent conditioning and optional multi-scale residuals.

        Args:
            masks: Tensor of shape [B, T, 1, H, W] or [B, 1, H, W] or [B, T, H, W].
            target_latent_shape: Optional (H_lat, W_lat) target resolution for exact alignment.
            num_frames: Optional frame count T to expand 4D static masks.

        Returns:
            SpatialAdapterOutput containing latent_conditioning and down_block_residuals.
        """
        # Normalize input dimensions to 5D [B, T, C, H, W]
        if masks.ndim == 4:
            # Could be [B, 1, H, W] or [B, T, H, W]
            if masks.shape[1] == 1:
                # [B, 1, H, W] static mask -> repeat along T if num_frames is provided
                t_frames = num_frames or 25
                masks_5d = masks.unsqueeze(1).repeat(1, t_frames, 1, 1, 1)
            else:
                # [B, T, H, W] -> unsqueeze channel dim
                masks_5d = masks.unsqueeze(2)
        elif masks.ndim == 5:
            masks_5d = masks
        else:
            raise ValueError(f"Expected 4D or 5D mask tensor, got shape {masks.shape}")

        b, t, c, h, w = masks_5d.shape

        # Fold (B * T) into batch dimension for 2D convolutions
        x = masks_5d.reshape(b * t, c, h, w)

        # 4 downsampling blocks
        feat0 = self.block1(x)      # [B*T, c0, H/2, W/2]
        feat1 = self.block2(feat0)  # [B*T, c1, H/4, W/4]
        feat2 = self.block3(feat1)  # [B*T, c2, H/8, W/8]
        feat3 = self.block4(feat2)  # [B*T, c3, H/8, W/8]

        # Temporal modeling across T frames
        if self.temporal_conv is not None and t > 1:
            # Reshape to [B * H_lat * W_lat, c3, T]
            _, c3_dim, h_lat, w_lat = feat3.shape
            feat3_temp = feat3.reshape(b, t, c3_dim, h_lat, w_lat).permute(0, 3, 4, 2, 1).reshape(b * h_lat * w_lat, c3_dim, t)
            # Residual 1D temporal conv
            feat3_temp = feat3_temp + self.temporal_conv(feat3_temp)
            # Restore shape [B*T, c3, H/8, W/8]
            feat3 = feat3_temp.reshape(b, h_lat, w_lat, c3_dim, t).permute(0, 4, 3, 1, 2).reshape(b * t, c3_dim, h_lat, w_lat)

        # Latent output head
        latent_out = self.latent_head(feat3)  # [B*T, C_latent, H/8, W/8]

        # Reshape back to [B, T, C_latent, H_lat, W_lat]
        c_lat = latent_out.shape[1]
        cur_h_lat, cur_w_lat = latent_out.shape[2], latent_out.shape[3]
        latent_5d = latent_out.reshape(b, t, c_lat, cur_h_lat, cur_w_lat)

        # Interpolate to target latent shape if specified and different
        if target_latent_shape is not None and (cur_h_lat, cur_w_lat) != target_latent_shape:
            tgt_h, tgt_w = target_latent_shape
            latent_folded = latent_5d.reshape(b * t, c_lat, cur_h_lat, cur_w_lat)
            latent_folded = F.interpolate(latent_folded, size=(tgt_h, tgt_w), mode="bilinear", align_corners=False)
            latent_5d = latent_folded.reshape(b, t, c_lat, tgt_h, tgt_w)

        # Multi-scale residuals if requested
        residuals: Optional[List[torch.Tensor]] = None
        if self.config.conditioning_type == "residual_injection":
            feats = [feat0, feat1, feat2, feat3]
            residuals = []
            for feat_i, head_i in zip(feats, self.residual_heads):
                res_i = head_i(feat_i)
                _, ch_i, h_i, w_i = res_i.shape
                residuals.append(res_i.reshape(b, t, ch_i, h_i, w_i))

        return SpatialAdapterOutput(
            latent_conditioning=latent_5d,
            down_block_residuals=residuals,
            conditioning_type=self.config.conditioning_type,
            metadata={
                "batch_size": b,
                "num_frames": t,
                "in_spatial_shape": (h, w),
                "latent_spatial_shape": latent_5d.shape[-2:],
                "parameter_count": self.parameter_count,
            },
        )

    def apply_to_latent(
        self,
        noisy_latents: torch.Tensor,
        masks: torch.Tensor,
    ) -> torch.Tensor:
        """Inject adapter features via residual latent addition."""
        target_shape = (noisy_latents.shape[-2], noisy_latents.shape[-1])
        adapter_out = self.forward(masks, target_latent_shape=target_shape, num_frames=noisy_latents.shape[1])
        return noisy_latents + adapter_out.latent_conditioning

    def apply_concat(
        self,
        noisy_latents: torch.Tensor,
        masks: torch.Tensor,
    ) -> torch.Tensor:
        """Inject adapter features via channel concatenation along latent dimension."""
        target_shape = (noisy_latents.shape[-2], noisy_latents.shape[-1])
        adapter_out = self.forward(masks, target_latent_shape=target_shape, num_frames=noisy_latents.shape[1])
        return torch.cat([noisy_latents, adapter_out.latent_conditioning], dim=2)


