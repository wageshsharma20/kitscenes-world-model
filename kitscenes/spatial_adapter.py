# 4. LIGHTWEIGHT MOCK SVD BACKBONE FOR CPU & FAST TESTING
# ==============================================================================


class MockSVDUNet(nn.Module):
    """Lightweight neural UNet conforming to diffusers UNetSpatioTemporalConditionModel interface.

    Allows fast CPU testing, parameter freezing validation, and gradient isolation checks
    without loading 9 GB SVD weights.
    """

    def __init__(
        self,
        in_channels: int = 8,
        out_channels: int = 4,
        block_out_channels: Tuple[int, ...] = (320, 640, 1280, 1280),
    ) -> None:
        super().__init__()
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.block_out_channels = block_out_channels

        # Backbone layers
        self.conv_in = nn.Conv2d(in_channels, 32, kernel_size=3, padding=1)
        self.mid_block = nn.Sequential(
            nn.Conv2d(32, 32, kernel_size=3, padding=1),
            nn.SiLU(),
        )
        self.conv_out = nn.Conv2d(32, out_channels, kernel_size=3, padding=1)
        nn.init.normal_(self.conv_out.weight, std=0.01)
        if self.conv_out.bias is not None:
            nn.init.zeros_(self.conv_out.bias)

    def forward(
        self,
        sample: torch.Tensor,
        timestep: Union[int, float, torch.Tensor],
        encoder_hidden_states: Optional[torch.Tensor] = None,
        added_time_ids: Optional[torch.Tensor] = None,
        return_dict: bool = True,
    ) -> Any:
        """Forward pass conforming to UNetSpatioTemporalConditionModel."""
        b, t, c, h, w = sample.shape
        x = sample.reshape(b * t, c, h, w)
        h_feat = self.conv_in(x)
        h_feat = self.mid_block(h_feat)
        out = self.conv_out(h_feat)
        pred = out.reshape(b, t, self.out_channels, h, w)

        if not return_dict:
            return (pred,)

        class MockUNetOutput:
            def __init__(self, sample_tensor: torch.Tensor) -> None:
                self.sample = sample_tensor

        return MockUNetOutput(pred)


