class MockSVDUNet(nn.Module):
    """Lightweight neural UNet conforming to diffusers UNetSpatioTemporalConditionModel interface.

    Allows fast CPU testing, parameter freezing validation, and gradient isolation checks
    without loading 9 GB SVD weights.
    """

    def __init__(
        self,
        in_channels: int = 8,
        out_channels: int = 4,
        block_out_channels: Tuple[int, ...] = (320, 640, 1280, 1280),
        cross_attention_dim: int = 1024,
        addition_time_embed_dim: int = 256,
        prediction_type: str = "v_prediction",
    ) -> None:
        super().__init__()
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.block_out_channels = block_out_channels
        self.cross_attention_dim = cross_attention_dim
        self.addition_time_embed_dim = addition_time_embed_dim
        self.prediction_type = prediction_type

        self.config = MockUNetConfig()
        self.config.in_channels = in_channels
        self.config.out_channels = out_channels
        self.config.block_out_channels = block_out_channels
        self.config.cross_attention_dim = cross_attention_dim
        self.config.addition_time_embed_dim = addition_time_embed_dim
        self.config.prediction_type = prediction_type

        # Backbone layers
        self.conv_in = nn.Conv2d(in_channels, 32, kernel_size=3, padding=1)
        self.mid_block = nn.Sequential(
            nn.Conv2d(32, 32, kernel_size=3, padding=1),
            nn.SiLU(),
        )
        self.conv_out = nn.Conv2d(32, out_channels, kernel_size=3, padding=1)
        nn.init.normal_(self.conv_out.weight, std=0.01)
        if self.conv_out.bias is not None:
            nn.init.zeros_(self.conv_out.bias)

        # Store last received kwargs for contract and integration verification
        self.last_forward_kwargs: Dict[str, Any] = {}

    def forward(
        self,
        sample: torch.Tensor,
        timestep: Union[int, float, torch.Tensor],
        encoder_hidden_states: Optional[torch.Tensor] = None,
        added_time_ids: Optional[torch.Tensor] = None,
        return_dict: bool = True,
        **kwargs: Any,
    ) -> Any:
        """Forward pass conforming to UNetSpatioTemporalConditionModel."""
        self.last_forward_kwargs = {
            "sample_shape": tuple(sample.shape),
            "timestep": timestep,
            "encoder_hidden_states": encoder_hidden_states,
            "added_time_ids": added_time_ids,
            "extra_kwargs": kwargs,
        }

        b, t, c, h, w = sample.shape
        x = sample.reshape(b * t, c, h, w)
        h_feat = self.conv_in(x)

        if encoder_hidden_states is not None:
            # Replicate UNet cross-attention autograd dependency
            ctx = encoder_hidden_states.mean(dim=1)  # [B, D] or [B*T, D]
            if ctx.shape[0] == b:
                ctx = ctx.unsqueeze(1).repeat(1, t, 1).reshape(b * t, -1)
            elif ctx.shape[0] != b * t:
                ctx = ctx.reshape(b * t, -1)
            d = ctx.shape[-1]
            if d >= 32:
                ctx_32 = ctx[:, :32]
            else:
                repeats = (32 + d - 1) // d
                ctx_32 = ctx.repeat(1, repeats)[:, :32]
            h_feat = h_feat + 0.01 * ctx_32.unsqueeze(-1).unsqueeze(-1)

        h_feat = self.mid_block(h_feat)
        out = self.conv_out(h_feat)
        pred = out.reshape(b, t, self.out_channels, h, w)

        if not return_dict:
            return (pred,)

        class MockUNetOutput:
            def __init__(self, sample_tensor: torch.Tensor) -> None:
                self.sample = sample_tensor

        return MockUNetOutput(pred)


